function translateLine(input: string, language: Language): string {
  const exact = EXACT[input]
  if (exact) return exact

  let result = input
  for (const [pattern, replacement] of PATTERNS) {
    if (pattern.test(result)) {
      result = result.replace(pattern, replacement)
      break
    }
  }

  // Keep real slash-command names, but expose English aliases in English text.
  const commands: string[] = []
  result = result.replace(/\/[А-Яа-яЁё-]+/g, command => {
    const english = language === 'en' ? COMMAND_EN[command] : undefined
    if (english) return english
    commands.push(command)
    return `\uE000${commands.length - 1}\uE001`
  })

  for (const [russian, english] of PHRASES) {
    if (result.includes(russian)) result = result.split(russian).join(english)
  }

  return result.replace(/\uE000([0-9]+)\uE001/g, (_, index) => commands[Number(index)] ?? '')
}

export function translateText(input: string, language = activeLanguage()): string {
  if (language === 'ru' || !input) return input
  const exact = EXACT[input]
  if (exact) return exact
  return input
    .split('\n')
    .map(line => translateLine(line, language))
    .join('\n')
}

function clamp(text: string, limit: number): string {
  return text.length > limit ? `${text.slice(0, Math.max(0, limit - 1))}…` : text
}

export function localizeEmbedJSON<T extends Record<string, unknown>>(
  embed: T,
  language = activeLanguage(),
): T {
  if (language === 'ru' || !embed) return embed
  const next = { ...embed } as Record<string, unknown>
  if (typeof next.title === 'string') {
    next.title = clamp(translateText(next.title, language), 256)
  }
  if (typeof next.description === 'string') {
    next.description = clamp(translateText(next.description, language), 4096)
  }
  if (next.footer && typeof next.footer === 'object') {
    const footer = next.footer as Record<string, unknown>
    next.footer = {
      ...footer,
      ...(typeof footer.text === 'string'
        ? { text: clamp(translateText(footer.text, language), 2048) }
        : {}),
    }
  }
  if (next.author && typeof next.author === 'object') {
    const author = next.author as Record<string, unknown>
    next.author = {
      ...author,
      ...(typeof author.name === 'string'
        ? { name: clamp(translateText(author.name, language), 256) }
        : {}),
    }
  }
  if (Array.isArray(next.fields)) {
    next.fields = next.fields.map(field => {
      const entry = field as Record<string, unknown>
      return {
        ...entry,
        ...(typeof entry.name === 'string'
          ? { name: clamp(translateText(entry.name, language), 256) }
          : {}),
        ...(typeof entry.value === 'string'
          ? { value: clamp(translateText(entry.value, language), 1024) }
          : {}),
      }
    })
  }
  return next as T
}

export function localizeComponentJSON<T>(component: T, language = activeLanguage()): T {
  if (language === 'ru' || !component || typeof component !== 'object') return component
  const next = { ...(component as Record<string, unknown>) }
  if (typeof next.label === 'string') {
    const limit = next.type === 2 ? 80 : next.type === 4 ? 45 : 100
    next.label = clamp(translateText(next.label, language), limit)
  }
  if (typeof next.placeholder === 'string') {
    next.placeholder = clamp(translateText(next.placeholder, language), 150)
  }
  if (typeof next.title === 'string') {
    next.title = clamp(translateText(next.title, language), 45)
  }
  if (Array.isArray(next.options)) {
    next.options = next.options.map(option => {
      const entry = option as Record<string, unknown>
      return {
        ...entry,
        ...(typeof entry.label === 'string'
          ? { label: clamp(translateText(entry.label, language), 100) }
          : {}),
        ...(typeof entry.description === 'string'
          ? { description: clamp(translateText(entry.description, language), 100) }
          : {}),
      }
    })
  }
  if (Array.isArray(next.components)) {
    next.components = next.components.map(child => localizeComponentJSON(child, language))
  }
  return next as T
}

export function localizeOptions(options: unknown): unknown {
  if (typeof options === 'string') return translateText(options)
  if (!options || typeof options !== 'object') return options
  if (typeof (options as { toJSON?: unknown }).toJSON === 'function') return options

  const next = { ...(options as Record<string, unknown>) }
  if (typeof next.content === 'string') next.content = translateText(next.content)
  if (Array.isArray(next.embeds)) {
    next.embeds = next.embeds.map(embed =>
      embed && typeof (embed as { toJSON?: unknown }).toJSON === 'function'
        ? embed
        : localizeEmbedJSON(embed as Record<string, unknown>),
    )
  }
  if (Array.isArray(next.components)) {
    next.components = next.components.map(component =>
      component && typeof (component as { toJSON?: unknown }).toJSON === 'function'
        ? component
        : localizeComponentJSON(component),
    )
  }
  return next
}
