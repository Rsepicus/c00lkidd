import { AsyncLocalStorage } from 'node:async_hooks'
import type { Language } from './names'

const languageStorage = new AsyncLocalStorage<Language>()

export function withLanguage<T>(language: Language, fn: () => T): T {
  return languageStorage.run(language, fn)
}

export function activeLanguage(): Language {
  return languageStorage.getStore() ?? 'ru'
}

export function setActiveLanguage(language: Language): void {
  languageStorage.enterWith(language)
}

